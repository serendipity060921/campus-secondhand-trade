-- 05-index-tuning.sql —— 索引审查与优化（v0.18 / 第1批-④）
--
-- 【为什么必须"另建库"来看执行计划】
--   演示库每张表只有 3~33 行，优化器在这个量级下**必然选全表扫描**，
--   直接看生产库的 EXPLAIN 会得到假阳性（没有索引问题也显示 ALL）。
--   因此审查在独立库 campus_trade_perf 上进行：结构与生产库完全一致（含全部索引），
--   灌入真实量级（商品 5 万 / 行为 20 万 / 消息 5 万 / 订单 2 万 / 收藏 3 万 / 图片 10 万），
--   再对项目真实使用的 **21 种查询形态** 逐条 EXPLAIN，并用 EXPLAIN ANALYZE 看真实耗时。
--   完整报告：docs/数据库性能与索引审查.md　可复跑：tools/index-review.py
--
-- 【审查结论：只采纳 1 个索引】
--   21 条查询中初始有 6 条出现 "Using filesort"，但逐条追查后只有 1 条是**真实瓶颈**，
--   其余 5 条经实测判定为"不值得加索引"，理由见本文件末尾 —— 这份"拒绝清单"与
--   采纳清单同等重要：索引不是越多越好，每个索引都要付出写入与维护成本。
-- ============================================================================

USE campus_trade;

-- ============================================================================
-- 唯一采纳项：商品按价格排序
-- ============================================================================
-- 场景：商品列表选择"价格升序/降序"（前端有该排序项，走 idx_status 之外无索引可用）。
-- 实测（5 万件商品，LIMIT 12 取前 12 条）：
--   优化前：type=ref key=idx_status rows=24876 Extra=Using filesort
--   优化后：type=ref key=idx_status_price rows=24876 Extra=Using where（无排序）
--   EXPLAIN ANALYZE 实测：Index lookup on idx_status_price ... (actual time=2.95..2.96 rows=12)
--     —— 实际只读取 12 行、2.96 ms；优化前需要把 24,876 行取出后排序。
-- 说明：这里"rows=24876"是优化器的估算值，与 EXPLAIN ANALYZE 的实际读取行数（12 行）
--       不同 —— 因为索引本身有序，配合 LIMIT 可以提前终止。这也是为什么要看 ANALYZE。
CREATE INDEX `idx_status_price` ON `product` (`status`, `price`);

-- ============================================================================
-- ★ 拒绝清单（看着像问题，实测判定不值得加索引）
-- ============================================================================
-- ① 商品列表(分类)：现有 idx_create_time 倒序扫描
--    实测 EXPLAIN ANALYZE：(actual time=0.0642..1.16 rows=398) —— 1.16 ms。
--    原因：有 LIMIT 12 时，倒序索引扫描找到 12 条匹配即可停止；
--    加 (status, category_id, create_time) 反而要扫 1440 行（更慢）。
--    ★ 教训：**"Using filesort" 不等于性能问题** —— 小 LIMIT 下 MySQL 用优先队列，
--      排序代价极低；判断必须看实际耗时，而不是看 Extra 里有没有 filesort。
--
-- ② 我的商品（seller_id 过滤 + create_time 倒序）：现有 idx_seller_id
--    实测只扫 10 行，排序 10 行的代价可忽略；希望以"职业卖家"偏斜场景验证收益，
--    但造数脚本未成功，**没有证据就不加索引**（宁缺勿滥）。
--
-- ③ 收藏夹列表：uk_user_product(user_id, product_id) 已能按 user_id 定位，
--    单个用户的收藏量天然有限（实测 6 行），排序代价可忽略 → 不加。
--
-- ④⑤ 买家/卖家订单列表：现有 (buyer_id, status) / (seller_id, status)
--    实测各只命中 4 行；尝试换成 (…, create_time) 后优化器**仍然选择原索引**并 filesort
--    （4 行的排序），说明换成 create_time 并不能改变执行计划 → 改动无收益，遂**撤回**。
--
-- ⑥ 会话列表（from_user_id=? OR to_user_id=?）：OR 条件无法用单个索引消除排序，
--    优化器已选择 index_merge + sort_union（实测 20 行），属该查询形态的合理方案 → 不加。
--
-- ⑦ 商品关键词模糊查询（LIKE '%教材%'）：前置通配符无法走索引，这是设计取舍
--    （校园场景下关键词量小、且已有分类与排序兜底），需全文检索时应引入 MySQL 全文索引
--    或 Elasticsearch，不属于本次索引调整范围。

